#!/usr/bin/env node
// Generates the branded illustration set:
//   public/images/illustrations/spec/<name>.svg  isometric property-spec scenes
//   public/images/illustrations/soft/<name>.svg  soft 3D icons used inside pages
//   src/shared/illustrations/generated/names.ts  the name lists, for typing
//   docs/illustrations-preview.html              every icon on one page
//
// Run: node scripts/illustrations/generate.mjs
// Uses the pre-installed Chromium (via Playwright) once, to crop each spec
// scene to its drawn bounds so all of them sit the same way in a tile.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ISO, renderIso } from './iso.mjs';
import { SOFT, renderSoft } from './soft.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const specDir = join(root, 'public/images/illustrations/spec');
mkdirSync(specDir, { recursive: true });
const softDir = join(root, 'public/images/illustrations/soft');
mkdirSync(softDir, { recursive: true });

const svg = (viewBox, defs, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="${viewBox}">${defs}${body}</svg>\n`;

// Spec scenes are drawn on a generous canvas, then cropped to a 6:5 box
// around what was actually drawn, with a little air on every side.
const specNames = Object.keys(ISO);
const raw = Object.fromEntries(specNames.map((n) => [n, renderIso(n)]));

async function measure() {
  const { chromium } = await import('playwright');
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium' });
  const page = await browser.newPage();
  const html = specNames.map((n) => `<svg id="${n}" width="400" height="400" viewBox="0 0 400 400">${raw[n].defs}<g>${raw[n].body}</g></svg>`).join('');
  await page.setContent(`<html><body>${html}</body></html>`);
  const boxes = await page.evaluate((names) => Object.fromEntries(names.map((n) => {
    const b = document.querySelector(`#${n} > g`).getBBox();
    return [n, { x: b.x, y: b.y, w: b.width, h: b.height }];
  })), specNames);
  await browser.close();
  return boxes;
}

const boxes = await measure();
for (const n of specNames) {
  const b = boxes[n];
  const pad = 6;
  let w = b.w + pad * 2, h = b.h + pad * 2;
  const ratio = 6 / 5;
  if (w / h > ratio) h = w / ratio; else w = h * ratio;
  const x = b.x + b.w / 2 - w / 2, y = b.y + b.h / 2 - h / 2;
  const vb = [x, y, w, h].map((v) => v.toFixed(1)).join(' ');
  writeFileSync(join(specDir, `${n}.svg`), svg(vb, raw[n].defs, raw[n].body));
}

const softNames = Object.keys(SOFT);
for (const n of softNames) {
  const { defs, body } = renderSoft(n);
  writeFileSync(join(softDir, `${n}.svg`), svg('-2 -2 68 70', defs, body));
}

const tsList = (a) => a.map((n) => `  '${n}',`).join('\n');
writeFileSync(
  join(root, 'src/shared/illustrations/generated/names.ts'),
  `// Generated by scripts/illustrations/generate.mjs — do not edit by hand.\n\n` +
  `export const SPEC_ILLUSTRATIONS = [\n${tsList(specNames)}\n] as const;\n\n` +
  `export const SOFT_ICONS = [\n${tsList(softNames)}\n] as const;\n`,
);

const cell = (src, n) => `<figure><img src="${src}" alt=""><figcaption>${n}</figcaption></figure>`;
writeFileSync(
  join(root, 'docs/illustrations-preview.html'),
  `<!doctype html><meta charset="utf-8"><title>BalkanEstate illustrations</title>
<style>body{font:14px system-ui;margin:24px;background:#F3F5F9;color:#0E1726}h2{margin:28px 0 12px}
.g{display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:12px}
figure{margin:0;background:#fff;border:1px solid #E1E6EF;border-radius:16px;padding:12px;text-align:center}
figure img{width:100%;aspect-ratio:6/5;object-fit:contain}
figcaption{font-size:12px;color:#5A6578;margin-top:6px}.s figure img{width:56px;height:56px;aspect-ratio:auto}</style>
<h2>Property specs</h2><div class="g">${specNames.map((n) => cell(`../public/images/illustrations/spec/${n}.svg`, n)).join('')}</div>
<h2>Soft icons</h2><div class="g s">${softNames.map((n) => cell(`../public/images/illustrations/soft/${n}.svg`, n)).join('')}</div>
`,
);

console.log(`spec illustrations: ${specNames.length}, soft icons: ${softNames.length}`);
